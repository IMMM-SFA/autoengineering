"""Trusted fake executable fixture for process/journal integration tests.

This fixture is not a security boundary and is never a provider host. Programs
must be supplied by the trusted test caller, not generated by an agent.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
import threading

from autoengineering.campaign.artifacts import confined_file

from ..process import supervise_process
from ..records import HostCapabilities, TaskAssignment
from .base import HostResult, InvocationContext


class ExecutableFakeHost:
    def __init__(self, program: Path):
        self.program = confined_file(program.parent, program.name)
        self._active: dict[str, threading.Event] = {}
        self._stopped: set[str] = set()

    def capabilities(self) -> HostCapabilities:
        identity = hashlib.sha256(self.program.read_bytes()).hexdigest()
        return HostCapabilities(
            "1.0",
            "fake",
            "1.0",
            f"trusted-fixture-{identity}",
            "none",
            True,
            True,
            None,
            "posix-test-fixture",
        )

    def invoke(self, *args, **kwargs):
        raise ValueError("executable fixture requires a reserved invocation context")

    def invoke_supervised(
        self, task: TaskAssignment, prompt: str, context: InvocationContext
    ) -> HostResult:
        stop = threading.Event()
        self._active[context.invocation_id] = stop
        try:
            result = supervise_process(
                (str(self.program),),
                directory=context.directory,
                cwd=self.program.parent,
                environment={"PATH": "/usr/bin:/bin", "HOME": str(self.program.parent)},
                nonce=context.nonce,
                stdin=prompt.encode(),
                timeout_seconds=context.timeout_seconds,
                max_output_bytes=context.max_output_bytes,
                on_launch=context.on_launch,
                cancelled=lambda: stop.is_set() or context.cancelled(),
            )
        finally:
            self._active.pop(context.invocation_id, None)
        if result.stopped:
            self._stopped.add(context.invocation_id)
        status = (
            result.status
            if result.status
            in (
                "completed",
                "timeout",
                "cancelled",
                "reconciliation_required",
            )
            else "host_failure"
        )
        try:
            text = result.stdout.decode("utf-8")
        except UnicodeError:
            status, text = "host_failure", ""
        return HostResult(
            status,
            text,
            None,
            {},
            result.elapsed_seconds,
            result.stdout,
            result.stderr,
            result.stopped,
        )

    def cancel(self, invocation_id: str) -> bool:
        if invocation_id in self._stopped:
            return True
        event = self._active.get(invocation_id)
        if event is not None:
            event.set()
        return False
